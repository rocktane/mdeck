import Cocoa

/// A pasteboard whose whole content is one web link, with every representation the copying
/// app put next to it (Safari's page title, a plist of URLs, an HTML anchor…), so the link can
/// be swapped for its clean version without losing the rest.
struct PasteboardLink {
    /// Markers of copies that must be left alone: secrets (password managers, the OS) and
    /// writes made by clipboard managers themselves — pasting a link from their history is a
    /// deliberate choice.
    static let ignoredMarkers: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.apple.is-sensitive"),
        .init("com.agilebits.onepassword"),
        .init("com.tinycast.internal"),
        .init("org.p0deje.Maccy"),
        .init("de.petermaurer.TransientPasteboardType"),
        .init("com.typeit4me.clipping"),
        .init("Pasteboard generator type"),
        .init("net.antelle.keeweb"),
    ]

    let link: String
    let changeCount: Int
    /// In the order the copying app declared them.
    let representations: [(NSPasteboard.PasteboardType, Data)]

    /// Nil unless the pasteboard holds a single item whose text is an http(s) link and nothing
    /// marks it as off-limits.
    static func read(from pasteboard: NSPasteboard) -> PasteboardLink? {
        let changeCount = pasteboard.changeCount
        guard let items = pasteboard.pasteboardItems, items.count == 1, let item = items.first else { return nil }
        let types = item.types
        guard Set(types).isDisjoint(with: ignoredMarkers),
              !types.contains(.fileURL) else { return nil }
        let text = item.string(forType: .string) ?? item.string(forType: .URL)
        guard let text, let link = LinkCleaner.link(in: text) else { return nil }
        // Only small, plain representations travel along; anything else would mean the copy
        // is more than a link (an image, a document) and is left alone.
        var representations: [(NSPasteboard.PasteboardType, Data)] = []
        for type in types {
            guard let data = item.data(forType: type) else { continue }
            guard data.count <= 256 * 1024 else { return nil }
            representations.append((type, data))
        }
        return PasteboardLink(link: link, changeCount: changeCount, representations: representations)
    }

    /// Every representation with the link replaced: as text (plain, URL, HTML with `&amp;`,
    /// RTF) or inside a property list. Binary data that cannot be read as either is kept as is.
    func replacing(with clean: String) -> [(NSPasteboard.PasteboardType, Data)] {
        let escaped = Self.htmlEscaped(link)
        let pairs = [(link, clean)] + (escaped == link ? [] : [(escaped, Self.htmlEscaped(clean))])
        return representations.map { type, data in
            if type == .string || type == .URL {
                return (type, Data(clean.utf8))
            }
            if let plist = Self.replacingInPlist(data, link, clean) { return (type, plist) }
            for encoding in [String.Encoding.utf8, .utf16] {
                guard let text = String(data: data, encoding: encoding), pairs.contains(where: { text.contains($0.0) }) else { continue }
                var result = text
                for (old, new) in pairs { result = result.replacingOccurrences(of: old, with: new) }
                if let encoded = result.data(using: encoding) { return (type, encoded) }
            }
            return (type, data)
        }
    }

    /// Replaces the pasteboard's content; returns the new change count.
    @discardableResult
    static func write(_ representations: [(NSPasteboard.PasteboardType, Data)], to pasteboard: NSPasteboard) -> Int {
        let item = NSPasteboardItem()
        for (type, data) in representations { item.setData(data, forType: type) }
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    private static func htmlEscaped(_ text: String) -> String {
        text.replacingOccurrences(of: "&", with: "&amp;")
    }

    private static func replacingInPlist(_ data: Data, _ old: String, _ new: String) -> Data? {
        let isPlist = data.starts(with: Array("bplist0".utf8)) || data.starts(with: Array("<?xml".utf8))
        guard isPlist,
              let object = try? PropertyListSerialization.propertyList(from: data, format: nil) else { return nil }
        func replace(_ value: Any) -> Any {
            switch value {
            case let string as String: return string.trimmingCharacters(in: .whitespacesAndNewlines) == old ? new : string
            case let array as [Any]: return array.map(replace)
            case let dictionary as [String: Any]: return dictionary.mapValues(replace)
            default: return value
            }
        }
        let format: PropertyListSerialization.PropertyListFormat = data.starts(with: Array("bplist0".utf8)) ? .binary : .xml
        return try? PropertyListSerialization.data(fromPropertyList: replace(object), format: format, options: 0)
    }
}
